export const getBuildingClassDescription = (code) => {
  if (!code) return 'Standard Property';
  const cleanCode = String(code).trim().toUpperCase();
  if (NYC_BUILDING_CLASS_GLOSSARY[cleanCode]) {
    return NYC_BUILDING_CLASS_GLOSSARY[cleanCode];
  }
  // Try 1-character prefix fallback
  const prefix = cleanCode.charAt(0);
  switch (prefix) {
    case 'A': return `One Family Dwelling (${cleanCode})`;
    case 'B': return `Two Family Dwelling (${cleanCode})`;
    case 'C': return `Walk-up Apartment (${cleanCode})`;
    case 'D': return `Elevator Apartment (${cleanCode})`;
    case 'E': return `Warehouse (${cleanCode})`;
    case 'F': return `Factory - Industrial (${cleanCode})`;
    case 'G': return `Garage / Gas Station (${cleanCode})`;
    case 'H': return `Hotel (${cleanCode})`;
    case 'I': return `Hospital / Health Facility (${cleanCode})`;
    case 'J': return `Theatre / Entertainment (${cleanCode})`;
    case 'K': return `Store Building / Retail (${cleanCode})`;
    case 'L': return `Loft Building (${cleanCode})`;
    case 'M': return `Religious / Community Facility (${cleanCode})`;
    case 'O': return `Office Building (${cleanCode})`;
    case 'R': return `Condominium (${cleanCode})`;
    case 'S': return `Mixed Commercial / Residential (${cleanCode})`;
    case 'V': return `Vacant Land (${cleanCode})`;
    case 'W': return `Educational Facility (${cleanCode})`;
    case 'Y': return `Government Facility (${cleanCode})`;
    default: return `Building Class (${cleanCode})`;
  }
};

export const getSpecialDistrictDescription = (code) => {
  if (!code) return 'None';
  const clean = String(code).trim().toUpperCase();
  for (const [key, value] of Object.entries(NYC_SPECIAL_DISTRICTS_GLOSSARY)) {
    if (key.toUpperCase() === clean || clean.includes(key.toUpperCase())) {
      return value;
    }
  }
  return clean;
};
